export function generateMockApplications(jobs) {
  const statuses = ['success', 'viewed', 'interview', 'rejected'];
  const statusWeights = [0.4, 0.3, 0.15, 0.15];
  
  return jobs.map((job, index) => {
    const rand = Math.random();
    let status = 'success';
    let cumulative = 0;
    
    for (let i = 0; i < statuses.length; i++) {
      cumulative += statusWeights[i];
      if (rand < cumulative) {
        status = statuses[i];
        break;
      }
    }
    
    const appliedAt = new Date(Date.now() - index * 3600000);
    
    return {
      id: `app_demo_${Date.now()}_${index}`,
      jobId: job.id,
      jobTitle: job.title,
      company: job.company,
      salary: job.salary.raw,
      status,
      appliedAt: appliedAt.toISOString(),
      responseTime: new Date(appliedAt.getTime() + Math.random() * 86400000).toISOString(),
      notes: status === 'success' ? '简历待确认' : 
             status === 'viewed' ? 'HR已查看' :
             status === 'interview' ? '面试已安排' : '岗位不匹配'
    };
  });
}
